    <h1>Tentang VoiXLib</h1>
  </div>
  <div class="reader-content" style="max-width:640px;padding-bottom:80px;font-size:17px;line-height:1.8">
    <p>VoiXLib adalah platform discovery dan perpustakaan pribadi untuk anime, manga, dan manhwa.
      Ia lahir dari satu pertanyaan: <em>seperti apa tempat yang tenang untuk menemukan dan menikmati cerita?</em></p>
    <p>Seluruh data katalog — judul, sampul, sinopsis, genre, status, skor, dan popularitas — diambil
      langsung dari <strong>AniList</strong>, database terbuka yang dikelola komunitas. VoiXLib tidak
      mengarang satu pun data itu. Jika sebuah informasi tidak tersedia, kami menampilkan
      “Tidak tersedia”, bukan mengisinya dengan karangan.</p>
    <p>VoiXLib adalah platform discovery: kami memetakan katalog, membantumu memilih, dan mengarahkanmu
      ke platform pembaca resmi yang berlisensi. Masuk dengan Discord untuk menyimpan rak pribadi,
      bookmark, dan riwayat yang tersinkron di semua perangkat.</p>
    <p style="color:var(--ink-2)">VoiXLib bukan afiliasi AniList maupun MyAnimeList, dan berterima kasih
      kepada komunitas yang menjaga datanya tetap terbuka.</p>
  </div>
