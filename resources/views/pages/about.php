    <h1>About VoiXLib</h1>
  </div>
  <div class="reader-content" style="max-width:640px;padding-bottom:80px;font-size:17px;line-height:1.8">
    <p>VoiXLib is an independent digital library for public-domain books. It exists to answer one question:
      <em>what would a calm place to read look like?</em></p>
    <p>The catalog is built on real, open sources — Project Gutenberg supplies the texts and most metadata,
      Gutendex provides its API, and Open Library fills in gaps like page counts, ISBNs and covers.
      When a book has no digitized cover, we design one from its own title, author and era rather than
      dropping in a placeholder.</p>
    <p>Reading happens in the browser with a reader built for long sessions: adjustable type, three paper
      tones, chapter navigation and bookmarks that remember your exact paragraph. Sign in with Discord and
      everything syncs; stay anonymous and it all stays politely on your device.</p>
    <p style="color:var(--ink-2)">VoiXLib is not affiliated with Project Gutenberg or the Internet Archive,
      but is grateful for them. Public-domain texts remain free forever, as they should be.</p>
